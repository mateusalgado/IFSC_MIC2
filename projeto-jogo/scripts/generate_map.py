"""Generate the shared wall bitmap used by rendering and collision (stdlib only)."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
data = json.loads((root/'assets/maps/map01.json').read_text())
width, height = data['width'], data['height']
assert (width, height, data['spawn'], data['goal']) == (160, 112, [12, 16], [144, 88])
walls = [True] * (width * height)


def clear(x0, y0, x1, y1):
    assert 0 < x0 <= x1 < width-1 and 0 < y0 <= y1 < height-1
    for y in range(y0, y1+1):
        for x in range(x0, x1+1):
            walls[y*width+x] = False


lo, hi = data['corridor_width']//2, (data['corridor_width']-1)//2
for path in [data['route'], *data['branches']]:
    for (ax, ay), (bx, by) in zip(path, path[1:]):
        assert ax == bx or ay == by
        clear(min(ax, bx)-lo, min(ay, by)-lo, max(ax, bx)+hi, max(ay, by)+hi)
for x, y in (data['spawn'], data['goal']):
    clear(x-7, y-7, x+6, y+6)
packed = [sum(int(walls[i+j]) << j for j in range(8)) for i in range(0, len(walls), 8)]
lines = [', '.join(f'0x{value:02x}' for value in packed[i:i+20]) for i in range(0, len(packed), 20)]
content = ('/* Generated by scripts/generate_map.py; edit assets/maps/map01.json. */\n'
           '#include "maze_map.h"\nconst uint8_t maze_map01[MAZE_BYTES] = {\n'
           + ''.join('    '+line+',\n' for line in lines) + '};\n')
target = root/'Game_Start2_STM32F411CE/Core/Src/maze_mapdata.c'
if args.check:
    assert target.read_text() == content, 'Map bitmap is stale; run generate_map.py'
else:
    target.write_text(content, newline='\n')
print(f'Map 01: {len(packed)} bytes, generated bitmap matches geometry.')
