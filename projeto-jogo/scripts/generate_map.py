"""Validate and generate the campaign wall bitmaps (Python standard library)."""
import argparse
from collections import deque
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()


def generate(data):
    width, height = data['width'], data['height']
    assert (width, height) == (160, 112)
    assert data['difficulty'] in (1, 2, 3)
    assert data['corridor_width'] == (14, 10, 8)[data['difficulty'] - 1]
    assert data['limit_ms'] == (60000, 50000, 40000)[data['difficulty'] - 1]
    assert data['route'][0] == data['spawn'] and data['route'][-1] == data['goal']
    assert data['spawn'] != data['goal']
    assert len(data['name']) <= 22 and all(32 <= ord(c) <= 126 for c in data['name'])
    walls = [True] * (width * height)

    def clear(x0, y0, x1, y1):
        assert 0 < x0 <= x1 < width - 1 and 0 < y0 <= y1 < height - 1
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                walls[y * width + x] = False

    lo, hi = data['corridor_width'] // 2, (data['corridor_width'] - 1) // 2
    for path in [data['route'], *data['branches']]:
        assert len(path) >= 2
        for (ax, ay), (bx, by) in zip(path, path[1:]):
            assert (ax == bx) != (ay == by), 'Need nonzero axis-aligned segments'
            clear(min(ax, bx)-lo, min(ay, by)-lo, max(ax, bx)+hi, max(ay, by)+hi)
    for x, y in (data['spawn'], data['goal']):
        clear(x-7, y-7, x+6, y+6)

    def free(x, y):
        return (2 <= x < width-2 and 2 <= y < height-2 and
                all(not walls[(y+dy)*width+x+dx] for dy in range(-2, 3) for dx in range(-2, 3)))

    # Verify the authored route using the whole player, not only a central pixel.
    length = 0
    for (ax, ay), (bx, by) in zip(data['route'], data['route'][1:]):
        length += abs(bx-ax) + abs(by-ay)
        for y in range(min(ay, by), max(ay, by)+1):
            for x in range(min(ax, bx), max(ax, bx)+1):
                assert free(x, y), 'Authored route cannot fit the 5x5 player'
    assert length / 24 < data['limit_ms'] / 1000, 'Route exceeds ideal time budget'

    spawn, goal = tuple(data['spawn']), tuple(data['goal'])
    distances = {spawn: 0}
    pending = deque([spawn])
    while pending:
        x, y = pending.popleft()
        for nx, ny in ((x-1, y), (x+1, y), (x, y-1), (x, y+1)):
            if (nx, ny) not in distances and free(nx, ny):
                distances[nx, ny] = distances[x, y] + 1
                pending.append((nx, ny))
    assert goal in distances, 'Goal unreachable by a 5x5 player'
    min_length, max_length = ((180, 260), (260, 380), (380, 520))[data['difficulty']-1]
    min_turns, max_turns = ((4, 6), (6, 8), (8, 12))[data['difficulty']-1]
    assert min_length <= length <= max_length, 'Route length outside difficulty budget'
    assert min_turns <= len(data['route'])-2 <= max_turns, 'Unexpected number of turns'
    assert distances[goal] >= length*0.8, 'Branch creates a major shortcut'
    packed = [sum(int(walls[i+j]) << j for j in range(8)) for i in range(0, len(walls), 8)]
    lines = [', '.join(f'0x{value:02x}' for value in packed[i:i+20]) for i in range(0, len(packed), 20)]
    symbol = f"maze_map{data['id']:02}"
    content = f'static const uint8_t {symbol}[MAZE_BYTES] = {{\n'
    content += ''.join('    '+line+',\n' for line in lines) + '};\n'
    sx, sy = spawn
    gx, gy = goal
    meta = (f'    {{{symbol}, {json.dumps(data["name"])}, {data["limit_ms"]}U, '
            f'{data["id"]}, {data["difficulty"]}, {data["corridor_width"]}, {sx}, {sy}, {gx}, {gy}}},\n')
    print(f'Map {data["id"]:02}: {len(packed)} bytes; route {length}px; '
          f'shortest 5x5 route {distances[goal]}px; {len(data["route"])-2} turns.')
    return content, meta, packed


content = '/* Generated by scripts/generate_map.py; edit assets/maps/map*.json. */\n#include "maze_map.h"\n'
metadata, masks = [], []
for map_id in range(1, 10):
    data = json.loads((root/f'assets/maps/map{map_id:02}.json').read_text())
    assert data['id'] == map_id
    assert data['difficulty'] == (map_id-1)//3+1
    bitmap, meta, packed = generate(data)
    content += bitmap
    metadata.append(meta)
    masks.append(packed)
assert all(masks[i] != masks[j] for i in range(9) for j in range(i))
content += 'const MazeMap maze_maps[MAZE_COUNT] = {\n' + ''.join(metadata) + '};\n'
# Compact practice arena with an obstacle; drawing and collision share these bits.
walls = [not (16 <= x < 144 and 40 <= y < 76) or (94 <= x < 102 and 40 <= y < 62)
         for y in range(112) for x in range(160)]
packed = [sum(int(walls[i+j]) << j for j in range(8)) for i in range(0, len(walls), 8)]
content += 'static const uint8_t tutorial_mask[MAZE_BYTES] = {\n'
for i in range(0, len(packed), 20):
    content += '    '+', '.join(f'0x{v:02x}' for v in packed[i:i+20])+',\n'
content += '};\nconst MazeMap maze_tutorial = {tutorial_mask, "TREINO", 0, 0, 1, 36, 24, 58, 130, 58};\n'
target = root/'Game_Start2_STM32F411CE/Core/Src/maze_mapdata.c'
if args.check:
    assert target.read_text() == content, 'Map catalog is stale; run generate_map.py'
else:
    target.write_text(content, newline='\n')
print('Nine-map campaign validated; generated catalog matches geometry.')
